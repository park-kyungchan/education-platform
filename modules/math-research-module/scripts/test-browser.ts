import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { moduleRoot } from './agent-platform';
const port=Number(process.env.TEST_PORT||4281);
const base=`http://127.0.0.1:${port}`;
const server=Bun.spawn([process.execPath,'scripts/serve.ts'],{cwd:moduleRoot,env:{...process.env,HOST:'127.0.0.1',PORT:String(port)},stdout:'pipe',stderr:'pipe'});
const assert=(value:unknown,message:string)=>{if(!value)throw Error(message);};
let browser;
try{
  let ready=false;
  for(let i=0;i<100;i++){try{if((await fetch(base)).ok){ready=true;break;}}catch{} await Bun.sleep(100);}
  if(!ready)throw Error('Browser test server did not start');
  browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors:string[]=[];const remoteRequests:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(!r.url().startsWith(base)&&!r.url().startsWith('data:'))remoteRequests.push(r.url());});
  await page.goto(base);await page.locator('.me-root').first().waitFor();
  assert(await page.locator('.me-root').count()===3,'Three domain entry points');
  assert(await page.locator('.module-status').textContent().then(s=>s?.includes('학습효과 미검증')),'Research boundary visible');
  await page.locator('.me-root').first().click();
  for(let i=0;i<4;i++)await page.locator('.me-row').first().click();
  assert(await page.locator('.context-column').count()===5,'Five hierarchy levels');
  await page.locator('.research-problem .me-primary').click();
  assert(await page.locator('.research-problem .answer-value').isVisible(),'Answer expands');
  await page.locator('.research-problem .me-primary').click();
  assert(await page.locator('.research-problem .answer-value').count()===0,'Repeated click collapses answer');
  await page.locator('.action-panel > summary').click();
  await page.locator('.action-steps button').nth(1).click();
  assert(await page.locator('.action-steps button[aria-pressed=true]').count()===1,'One action selection');
  await page.locator('[data-context-id="U-D"]').click();
  assert(await page.locator('.context-column').count()===2,'New domain clears descendants');
  assert(await page.locator('.answer-value').count()===0,'New navigation clears prior answer');
  await page.locator('.me-brand').click();
  assert(await page.locator('.me-root').count()===3,'Home restores roots');
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'Mobile home does not overflow horizontally');
  await page.locator('.me-root').nth(2).click();
  for(let i=0;i<4;i++)await page.locator('.me-row').first().click();
  assert(await page.locator('.research-problem').isVisible(),'Mobile research content visible');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'Mobile detail does not overflow horizontally');
  assert(!errors.length,`Runtime errors: ${errors.join('; ')}`);
  assert(!remoteRequests.length,`Unexpected background requests: ${remoteRequests.join('; ')}`);
  const output=resolve(moduleRoot,'.local/browser');await mkdir(output,{recursive:true});
  await page.screenshot({path:resolve(output,'mobile-detail.png'),fullPage:true});
  const report={checkedAt:new Date().toISOString(),browser:await browser.version(),environment:'dot cloud Chromium',checks:['home domains','five-level navigation','answer repeated toggle','single action selection','stale descendant cleanup','home return','mobile home/detail overflow','no runtime errors','no third-party background requests'],result:'pass',errors,remoteRequests,limitations:['Representative browser paths only; all 151 designs and 1216 actions are additionally covered by DOM tests.','Target WSL2/VPS execution and empirical learning effects were not tested.']};
  await writeFile(resolve(output,'report.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
}finally{await browser?.close();server.kill();await server.exited;}
